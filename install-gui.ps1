function Test-Installed {
    param([string]$Path)
    if (-not (Test-Path $Path)) { return $false }
    $content = Get-Content $Path -Raw -ErrorAction SilentlyContinue
    return ($content -and $content.Contains($MARKER_START))
}

function Ensure-Profile {
    param([string]$Path)
    if (-not $Path) { return }
    $dir = Split-Path -Parent $Path
    if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    if (-not (Test-Path $Path)) { New-Item -ItemType File -Path $Path -Force | Out-Null }
}

function Remove-ProfileBlock {
    param([string]$Path)
    if (-not (Test-Path $Path)) { return }
    $content = Get-Content $Path -Raw
    if (-not $content) { return }
    $content = [regex]::Replace($content, "(?s)[\r\n]*" + [regex]::Escape($MARKER_START) + ".*?" + [regex]::Escape($MARKER_END) + "[\r\n]*", "`r`n")
    $content = $content.TrimStart("`r", "`n")
    [System.IO.File]::WriteAllText($Path, $content, [System.Text.Encoding]::UTF8)
}

function Get-BinDirFromProfile {
    param([string]$Path)
    if (-not (Test-Path $Path)) { return "" }
    $content = Get-Content $Path -Raw -ErrorAction SilentlyContinue
    if (-not $content) { return "" }
    $m = [regex]::Match($content, '\$env:Path\s*=\s*"([^"]*?);\$env:Path"')
    if ($m.Success) { return $m.Groups[1].Value }
    return ""
}

function Get-FunctionBlock {
    param([string]$ProfilePath)
    $gw = $GW_SCRIPT.Replace("'", "''")
    @"
$MARKER_START
function gitwhisper { & '$gw' @args }
$MARKER_END
"@
}

function Get-BinBlock {
    param([string]$BinPath)
    @"
$MARKER_START
`$env:Path = "$BinPath;`$env:Path"
$MARKER_END
"@
}

function Install-All {
    param([string]$ProfilePath, [string]$Type, [string]$BinPath)
    Ensure-Profile $ProfilePath
    Remove-ProfileBlock $ProfilePath
    if ($Type -eq "bin") {
        New-Item -ItemType Directory -Path $BinPath -Force | Out-Null
        $cmd = "@echo off`r`npowershell -NoProfile -ExecutionPolicy Bypass -File `"$($GW_SCRIPT.Replace('"', '""'))`" %*`r`n"
        [System.IO.File]::WriteAllText((Join-Path $BinPath "gitwhisper.cmd"), $cmd, [System.Text.Encoding]::ASCII)
        $shim = "#!/usr/bin/env pwsh`r`n# Generated by the GitWhisper installer.`r`n& '$($GW_SCRIPT.Replace("'", "''"))' @args`r`n"
        [System.IO.File]::WriteAllText((Join-Path $BinPath "gitwhisper.ps1"), $shim, [System.Text.Encoding]::UTF8)
        if (-not ($env:Path -split ";" -contains $BinPath)) {
            Add-Content -Path $ProfilePath -Value "`r`n$(Get-BinBlock $BinPath)" -Encoding UTF8
        }
    } else {
        Add-Content -Path $ProfilePath -Value "`r`n$(Get-FunctionBlock $ProfilePath)" -Encoding UTF8
    }
}

function Uninstall-All {
    param([string]$ProfilePath, [string]$BinPath)
    $fromProfile = Get-BinDirFromProfile $ProfilePath
    Remove-ProfileBlock $ProfilePath
    $removed = @()
    foreach ($d in @($BinPath, $fromProfile)) {
        if (-not $d) { continue }
        foreach ($f in @((Join-Path $d "gitwhisper.cmd"), (Join-Path $d "gitwhisper.ps1"))) {
            if (Test-Path $f) { Remove-Item $f -Force; $removed += $f }
        }
    }
    return $removed
}

