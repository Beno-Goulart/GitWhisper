function Set-Status {
    param([string]$Msg, [string]$Color = "#3730a3")
    $txtStatus.Text = $Msg
    $txtStatus.Foreground = [System.Windows.Media.BrushConverter]::new().ConvertFromString($Color)
}

function Update-ProfilePreview {
    $p = $txtProfile.Text.Trim()
    $type = Get-CurrentType
    $b = $txtBinDir.Text.Trim()
    $lines = New-Object System.Collections.Generic.List[string]
    $installed = Test-Installed $p

    if ($type -eq "bin") {
        if (-not $b) { $b = Join-Path $HOME ".local\bin" }
        $lines.Add("Wrapper files to be created:")
        $lines.Add("  $b\gitwhisper.cmd")
        $lines.Add("  $b\gitwhisper.ps1")
        $lines.Add("")
        $lines.Add("Block to be appended to the profile:")
        $lines.Add("")
        $lines.Add((Get-BinBlock $b))
        $binInstalled = (Test-Path "$b\gitwhisper.cmd") -or (Test-Path "$b\gitwhisper.ps1")
        $statusBits = @()
        if ($installed) { $statusBits += "profile has a GitWhisper block" }
        if ($binInstalled) { $statusBits += "wrapper files already exist" }
        if ($statusBits.Count -eq 0) {
            $txtProfileStatus.Text = "Nothing installed yet - clicking Install will create these files."
        } else {
            $txtProfileStatus.Text = ($statusBits -join "; ") + " - Install will replace them."
        }
    } else {
        $lines.Add("Function to be appended to the profile:")
        $lines.Add("")
        $lines.Add((Get-FunctionBlock $p))
        if ($installed) {
            $txtProfileStatus.Text = "A GitWhisper block already exists in this profile - Install will replace it."
        } else {
            $txtProfileStatus.Text = "Nothing installed yet - clicking Install will append this function."
        }
    }

    if (-not $p) {
        $txtProfilePreview.Text = "Enter a profile file path to see the preview."
        $txtProfileStatus.Text = ""
        return
    }
    $txtProfilePreview.Text = ($lines -join "`r`n")
}

function Get-CheatSheet {
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine("Conventional Commit types + gitmoji")
    [void]$sb.AppendLine("====================================")
    foreach ($type in @("feat", "fix", "docs", "test", "style", "refactor", "perf", "build", "ci", "chore", "revert")) {
        [void]$sb.AppendLine(("{0,-9} {1}" -f $gitmoji[$type], $type))
    }
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("Generated messages look like:")
    [void]$sb.AppendLine("  " + $gitmoji["feat"] + " feat(auth): adds Login component")
    [void]$sb.AppendLine("  " + $gitmoji["fix"] + " fix(api): adds error handling in user.js")
    [void]$sb.AppendLine("  " + $gitmoji["docs"] + " docs: adds README.md")
    [void]$sb.AppendLine("  " + $gitmoji["test"] + " test(payments): covers refund flow")
    [void]$sb.AppendLine("  " + $gitmoji["perf"] + " perf(search): adds caching")
    [void]$sb.AppendLine("")
    [void]$sb.AppendLine("Type is inferred from your diff, with a fallback to")
    [void]$sb.AppendLine("the current branch name when it starts with feat/, fix/,")
    [void]$sb.AppendLine("docs/, test/, chore/, refactor/, perf/, style/, ci/, build/.")
    return $sb.ToString()
}

function Update-GwPreview {
    $txtGwPreview.Text = Get-CheatSheet
}

function Generate-DemoMessage {
    param([string]$Description)
    if (-not $Description) { $Description = "adds a small feature" }
    $tmp = Join-Path ([IO.Path]::GetTempPath()) ("gw-demo-" + [guid]::NewGuid().ToString("N"))
    try {
        New-Item -ItemType Directory -Path $tmp | Out-Null
        & git -C $tmp init -q
        $tree = (& git -C $tmp write-tree).Trim()
        $commit = "baseline" | & git -C $tmp commit-tree $tree
        & git -C $tmp update-ref HEAD $commit
        & git -C $tmp reset -q
        $word = ($Description -split "\s+" | Where-Object { $_ } | Select-Object -Last 1)
        $content = @"
const $word = { ok: true };
export default $word;
"@
        [System.IO.File]::WriteAllText((Join-Path $tmp "demo.js"), $content, [System.Text.Encoding]::UTF8)
        & git -C $tmp add demo.js
        Push-Location $tmp
        try { $out = & powershell -NoProfile -ExecutionPolicy Bypass -File $GW_SCRIPT suggest 2>&1 | Out-String }
        finally { Pop-Location }
        $out = $out.Trim()
        if (-not $out) { $out = "(no suggestion generated - the temp repo produced no diff)" }
        return $out
    }
    catch {
        return "Could not generate a live example: $($_.Exception.Message)"
    }
    finally {
        if (Test-Path $tmp) { Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue }
    }
}

function Show-ProjectDialog {
    $preader = New-Object System.Xml.XmlNodeReader([xml]$projXaml)
    $projWin = [System.Windows.Markup.XamlReader]::Load($preader)
    $projWin.Owner = $window

    $projDirBox   = $projWin.FindName("projDir")
    $projBrowse   = $projWin.FindName("projBrowse")
    $chkEmoji     = $projWin.FindName("chkEmoji")
    $cboDefault   = $projWin.FindName("cboDefault")
    $chkPrepare   = $projWin.FindName("chkPrepare")
    $chkValidate  = $projWin.FindName("chkValidate")
    $projApply    = $projWin.FindName("projApply")
    $projCancel   = $projWin.FindName("projCancel")

    $script:projDir = (Get-Location).Path
    $projDirBox.Text = $script:projDir

    $projBrowse.Add_Click({
        $dlg = New-Object System.Windows.Forms.FolderBrowserDialog
        $dlg.Description = "Select a git project directory"
        if ($projDirBox.Text) { $dlg.SelectedPath = $projDirBox.Text }
        if ($dlg.ShowDialog() -eq [System.Windows.Forms.DialogResult]::OK) {
            $projDirBox.Text = $dlg.SelectedPath
        }
    })

    $projCancel.Add_Click({ $projWin.DialogResult = $false; $projWin.Close() })
    $projApply.Add_Click({
        $d = $projDirBox.Text.Trim()
        if (-not $d) {
            [System.Windows.MessageBox]::Show("Choose a project directory.", "GitWhisper", "OK", "Warning") | Out-Null
            return
        }
        $script:projDir = $d
        $script:projEmoji    = if ($chkEmoji.IsChecked) { "y" } else { "n" }
        $script:projDefault  = [string]($cboDefault.SelectedIndex + 1)
        $script:projPrepare  = if ($chkPrepare.IsChecked) { "y" } else { "n" }
        $script:projValidate = if ($chkValidate.IsChecked) { "y" } else { "n" }
        $projWin.DialogResult = $true
        $projWin.Close()
    })

    return $projWin.ShowDialog()
}

function Do-ProjectSetup {
    if (-not (Test-Path $GW_SCRIPT)) {
        Set-Status "gitwhisper.ps1 not found next to this installer." "#b91c1c"
        return
    }
    if ((Show-ProjectDialog) -ne $true) { return }
    $dir = $script:projDir
    try {
        if (-not (Test-Path "$dir\.git")) {
            Set-Status "No .git directory found in $dir." "#b45309"
            return
        }
        $config = @"

# GitWhisper configuration
# Created by the GitWhisper installer.

[general]
emoji = $($script:projEmoji)
default = $($script:projDefault)

[hooks]
prepare = $($script:projPrepare)
validate = $($script:projValidate)
"@
        Set-Content -Path "$dir\.gitwhisperconfig" -Value $config.TrimStart() -Encoding UTF8
        Push-Location $dir
        try { & powershell -NoProfile -ExecutionPolicy Bypass -File $GW_SCRIPT init | Out-Null } finally { Pop-Location }
        Set-Status "Project $dir is ready (config + hooks installed)." "#15803d"
    }
    catch {
        Set-Status "Project setup failed: $($_.Exception.Message)" "#b91c1c"
    }
}

function Do-Install {
    $p = $txtProfile.Text.Trim()
    if (-not $p) {
        Set-Status "Enter a profile file path first." "#b91c1c"
        return
    }
    if (-not (Test-Path $GW_SCRIPT)) {
        Set-Status "gitwhisper.ps1 not found next to this installer." "#b91c1c"
        return
    }
    try {
        Install-All $p (Get-CurrentType) $txtBinDir.Text.Trim()
        Update-ProfilePreview
        Set-Status "Installed. Restart your terminal or run: . $PROFILE" "#15803d"
    }
    catch {
        Set-Status "Install failed: $($_.Exception.Message)" "#b91c1c"
    }
}

function Do-Uninstall {
    $p = $txtProfile.Text.Trim()
    if (-not $p) {
        Set-Status "Enter a profile file path first." "#b91c1c"
        return
    }
    if (-not (Test-Installed $p)) {
        Set-Status "GitWhisper is not installed in $p." "#b45309"
        return
    }
    try {
        $removed = Uninstall-All $p $txtBinDir.Text.Trim()
        Update-ProfilePreview
        $extra = if ($removed.Count -gt 0) { " Removed wrapper files." } else { "" }
        Set-Status "Uninstalled.$extra Restart your terminal or run: . $PROFILE" "#15803d"
    }
    catch {
        Set-Status "Uninstall failed: $($_.Exception.Message)" "#b91c1c"
    }
}

